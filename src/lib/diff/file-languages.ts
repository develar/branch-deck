/** File names and extensions that Shiki has no grammar for, by the grammar that reads them; they win over the table */
export const CUSTOM_EXTENSIONS: Readonly<Record<string, string>> = {
  gradle: "groovy",
  iml: "xml",
  ipr: "xml",
  iws: "xml",
  form: "xml",
  editorconfig: "ini",
  ".editorconfig": "ini",
  "Cargo.lock": "toml",
}

function lookUp(key: string): string | undefined {
  return Object.hasOwn(CUSTOM_EXTENSIONS, key) ? CUSTOM_EXTENSIONS[key] : Object.hasOwn(EXTENSION_LANGUAGES, key) ? EXTENSION_LANGUAGES[key] : undefined
}

/** The grammar of a name: the whole name (`Dockerfile`), a compound extension (`component.ts`), the extension */
function languageOfName(name: string): string | undefined {
  return lookUp(name) ?? lookUp(/\.([^/\\]+\.[^/\\]+)$/.exec(name)?.[1] ?? "") ?? lookUp(/\.([^.]+)$/.exec(name)?.[1] ?? "")
}

/**
 * The Shiki grammar of a path; "text" for a file without a bundled grammar. A path that matches nothing is looked up
 * again by its base name, so `docker/Dockerfile` reads as a `Dockerfile`, and a real extension still wins.
 */
export function languageOfPath(path: string): string {
  const baseName = path.split(/[/\\]/).pop() ?? path
  return languageOfName(path) ?? (baseName === path ? undefined : languageOfName(baseName)) ?? "text"
}
