/// Why a change of a file is mechanical: the review folds it into one group at the end
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize)]
#[cfg_attr(feature = "specta", derive(specta::Type))]
#[cfg_attr(feature = "schemars", derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase")]
pub enum MechanicalKind {
  /// A file of the build model (`*.iml`, `BUILD`, `BUILD.bazel`, `*.lock`, `pnpm-lock.yaml`, `.idea/modules.xml`), or a
  /// plugin descriptor, `Cargo.toml` or `package.json` that changed only in its dependency entries
  BuildModel,
  /// Only `import`, `use` and `package` lines and blank lines changed
  ImportsOnly,
  /// Only whitespace changed
  Whitespace,
  /// Moved, no line changed
  Renamed,
  /// Deleted
  Deleted,
  /// Nobody writes it by hand: a lock file, a file the attributes mark generated, a file whose header says a tool wrote
  /// it (`FileFacts::generated` says which)
  Generated,
}

/// Files that get the same edit: one hunk with the same removed and added lines, without whitespace
