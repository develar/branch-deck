//! The facts of each file of a review (spec/branch/review-plan.spec.md, "Files", "Mechanical changes", "Repeated
//! edits"): its links to the other changed files, whether its change is mechanical, the repeated edit it shares, the
//! usages of the API it removes or changes, and whether it changed without its tests.
//!
//! - **The files**: every path the reviewed commits change, once, at its last path: a renamed file at its new path with
//!   the path before the first commit, a deleted one at its path, none that the commits add and delete again.
//! - **Mechanical**, by name or by the text of every hunk of every commit that changes the file, as `ImportChangeFilter`
//!   of `CoRT` and `detectReformatting` of `SmartCommit` do: `Deleted` when the commits delete it, `Generated` for a
//!   file nobody writes by hand (`generated-files`: a lock file, a minified file or a source map by its name, the
//!   attributes of the head of the range, or the header a tool wrote into it; `generated_of`), `BuildModel`
//!   for a file of the build model (`*.iml`, `BUILD`, `BUILD.bazel`, another `*.lock`, `.idea/modules.xml`)
//!   and for a manifest whose parsed form changed only in its dependency entries (a plugin descriptor, `Cargo.toml`,
//!   `package.json`: `dependencies::ManifestState`). A manifest that does not parse, or that changed beside its
//!   dependencies, is no `BuildModel` (an `*.iml` that parses is one by name). Else each change a pure rename
//!   (status `R`, no line added or removed), or each of its hunks the same text without
//!   its whitespace, line ends included, so a wrapped or joined line too (`Whitespace`), or, in a source file, only
//!   blank lines and lines of import statements, at least one (`ImportsOnly`). A file whose whitespace has a meaning
//!   (Python, Starlark, YAML, a Makefile: `indentation_matters`) is never `Whitespace`. An import statement starts
//!   with an `import`, `use` or `package` line and runs until the brackets it opens close, so a Rust `use a::{` block
//!   or a TypeScript `import {` over several lines counts whole; a bracket in a string or a comment counts not, and a
//!   statement that a `;`, the next import line or the end of the text ends with its brackets open counts as its first
//!   line only. The lines are read in the whole blob, so a hunk inside such a block is an import hunk too. One import
//!   hunk makes the file `ImportsOnly`, else one whitespace hunk `Whitespace`. A file without text (binary, too large, an added one) is only mechanical by name or
//!   deletion.
//! - **Repeated edits**: never of a generated file, whose edit its tool made; the key of a hunk is the text of its
//!   removed and of its added lines without whitespace; a
//!   hunk of whitespace alone has none, nor one without a line of 10 or more characters. A key of 3 or more files
//!   makes a group, the key of the most files first; a file is in one group at most, and a group keeps at least 3 files
//!   that no larger group took.
//! - **Tests**, by the path: a directory `test`, `tests`, `__tests__` or `testFixtures`; a name `*Test`, `*Tests`
//!   (Kotlin, Java), `*_test` (Rust), `*.test`, `*.spec` (TypeScript) or `test_*`. Its subject is the stem without that
//!   mark (`FooTest.kt` and `foo.test.ts` name `Foo` and `foo`), compared without case; a file of a test directory names
//!   the stem it has. A source file (`code_symbols::language::language_of`), no test, still there and not mechanical,
//!   is `untested` when no changed test names its stem.
//! - **The text of the hunks** comes from the old and new blobs of the modified and the renamed files that are not
//!   mechanical by name or generated by their attributes (`hunk_blobs`), and the header from the new blob of every
//!   other file still there (`header_blobs`): from the memory of the diffs, else in the batch of the summaries
//!   (`trial_check::symbol_scan::read_symbol_input_with`). A blob too large for the summaries has no text, so no
//!   header either: such a file starts collapsed for its size anyway.

