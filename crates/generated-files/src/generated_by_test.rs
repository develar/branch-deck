use crate::attributes::marks_generated;
use crate::generated_by::{GeneratedBy, generated_by};
use crate::names::GeneratedName;
use pretty_assertions::assert_eq;

const STARLARK: &[u8] = b"# Generated by `plans-tool` - do not edit.\n\n_PLAN_A = [\"a\"]\n";

/// The name first, then the attributes, then the header of any version of the file; a file a person writes has none
#[test]
fn a_file_is_generated_by_its_name_its_attributes_or_the_header_of_a_version() {
  let plain: &[u8] = b"_PLAN_A = [\"a\"]\n";
  assert_eq!(generated_by("Cargo.lock", false, [plain]), Some(GeneratedBy::Name { name: GeneratedName::LockFile }));
  assert_eq!(generated_by("plans.bzl", true, [STARLARK]), Some(GeneratedBy::Attribute));
  assert_eq!(
    generated_by("plans.bzl", false, [plain, STARLARK]),
    Some(GeneratedBy::Header {
      line: "Generated by `plans-tool` - do not edit.".to_string()
    }),
    "the header of another version"
  );
  assert_eq!(generated_by("plans.bzl", false, [plain]), None);
  assert_eq!(generated_by("plans.bzl", false, std::iter::empty::<&[u8]>()), None);
}

/// A start cut inside a character keeps the text before it: the header is still read
#[test]
fn a_long_text_is_read_by_its_start() {
  let mut text = STARLARK.to_vec();
  text.extend("é".repeat(5000).bytes());
  assert!(generated_by("plans.bzl", false, [text.as_slice()]).is_some());
}

#[test]
fn linguist_generated_and_no_diff_mark_a_file_generated() {
  assert!(marks_generated("linguist-generated", "set"));
  assert!(marks_generated("linguist-generated", "true"));
  assert!(marks_generated("diff", "unset"));
  assert!(!marks_generated("linguist-generated", "false"));
  assert!(!marks_generated("linguist-generated", "unspecified"));
  assert!(!marks_generated("diff", "set"));
}

#[test]
fn the_reason_reads_as_words() {
  assert_eq!(
    GeneratedBy::Header {
      line: "Generated by `plans-tool` - do not edit.".to_string()
    }
    .describe(),
    "its header \"Generated by `plans-tool` - do not edit.\""
  );
  assert_eq!(GeneratedBy::Name { name: GeneratedName::LockFile }.describe(), "its name: a lock file");
  assert_eq!(GeneratedBy::Attribute.describe(), "its git attributes: linguist-generated or -diff");
}
