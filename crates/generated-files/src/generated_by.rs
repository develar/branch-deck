//! Why a file is generated, as a review and an update show it, and the one rule that tells it from what a caller read

use crate::header::{HEADER_BYTES, generated_header};
use crate::names::{GeneratedName, generated_name};
use serde::{Deserialize, Serialize};

/// Why a file is generated: its name, the attributes of the revision, the header a tool wrote into it, or, of a review
/// alone, the regions a tool writes that hold every line its change touched
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[cfg_attr(feature = "specta", derive(specta::Type))]
#[cfg_attr(feature = "schemars", derive(schemars::JsonSchema))]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum GeneratedBy {
  /// Its name (`Cargo.lock`, `*.min.js`)
  Name { name: GeneratedName },
  /// The attributes mark it `linguist-generated` or `-diff`
  Attribute,
  /// Its leading comment, without the comment markers: `Generated by render-guides.mjs; edit community/.ai/*`
  Header { line: String },
  /// Every line its change removed or added lies between the markers of a region a tool writes into a file a person
  /// writes too (`diff_marks::regions`): the name of the first, as written, as `auto-generated section 'build a.b'` (IntelliJ quotes the name with backticks).
  /// Only a review says it, of a change; `generated_by` never answers it, as the rest of the file is no tool's
  Region { name: String },
}

impl GeneratedBy {
  /// What says that the file is generated, in words: `its header "Generated by …"`, `its git attributes …`, `its name: a
  /// lock file`
  pub fn describe(&self) -> String {
    match self {
      Self::Name { name } => {
        let name = match name {
          GeneratedName::LockFile => "a lock file",
          GeneratedName::Minified => "a minified file",
          GeneratedName::SourceMap => "a source map",
          GeneratedName::Snapshot => "the snapshot of a test",
        };
        format!("its name: {name}")
      }
      Self::Attribute => "its git attributes: linguist-generated or -diff".to_string(),
      Self::Header { line } => format!("its header \"{line}\""),
      Self::Region { name } => format!("its region \"{name}\", which a tool writes"),
    }
  }
}

/// Why the file at `path` is generated: its name (`names::generated_name`), else its attributes (`marked`: one of them
/// `attributes::marks_generated`), else the header of the first of `texts` (versions of it, as stored) that starts with
/// one (`header::generated_header`); `None` for a file a person writes
pub fn generated_by<'a>(path: &str, marked: bool, texts: impl IntoIterator<Item = &'a [u8]>) -> Option<GeneratedBy> {
  if let Some(name) = generated_name(path) {
    return Some(GeneratedBy::Name { name });
  }
  if marked {
    return Some(GeneratedBy::Attribute);
  }
  texts.into_iter().find_map(|text| {
    let start = &text[..text.len().min(HEADER_BYTES)];
    // a start cut inside a character keeps the text before it
    let start = std::str::from_utf8(start).unwrap_or_else(|error| std::str::from_utf8(&start[..error.valid_up_to()]).unwrap_or_default());
    generated_header(path, start).map(|line| GeneratedBy::Header { line })
  })
}
