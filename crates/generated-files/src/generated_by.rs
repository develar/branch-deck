//! Why a file is generated, as a review shows it

use crate::names::GeneratedName;
use serde::Serialize;

/// Why a file is generated: its name, the attributes of the revision, or the header a tool wrote into it
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize)]
#[cfg_attr(feature = "specta", derive(specta::Type))]
#[cfg_attr(feature = "schemars", derive(schemars::JsonSchema))]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum GeneratedBy {
  /// Its name (`Cargo.lock`, `*.min.js`)
  Name { name: GeneratedName },
  /// The attributes mark it `linguist-generated` or `-diff`
  Attribute,
  /// Its leading comment, without the comment markers: `Generated by render-guides.mjs; edit community/.ai/*`
  Header { line: String },
}
